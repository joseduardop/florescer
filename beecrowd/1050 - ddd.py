# 1050 - DDD

# le o codigo de DDD
ddd = int(input())

# tabela de cidades por DDD
cidade = "DDD nao cadastrado"
if ddd == 11:
    cidade = "Sao Paulo"
if ddd == 21:
    cidade = "Rio de Janeiro"
if ddd == 32:
    cidade = "Juiz de Fora"
if ddd == 19:
    cidade = "Campinas"
if ddd == 27:
    cidade = "Vitoria"
if ddd == 31:
    cidade = "Belo Horizonte"

print(cidade)
